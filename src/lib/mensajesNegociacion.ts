/**
 * Bono 2 — "Plantillas de mensajes para negociar precios".
 *
 * Diccionario de mensajes en PORTUGUÉS (lo que el cliente copia y manda al
 * proveedor brasileño) con la traducción en ESPAÑOL (lo que el cliente lee).
 *
 * Estructura:
 *   BLOQUES → secciones → mensajes
 *   - bloque "paso-a-paso": vale para cualquier producto (saludo → envío).
 *   - bloques por grupo de categoría: sólo lo que cambia en ese rubro.
 *     Categorías con preguntas iguales se juntan en un mismo bloque.
 *
 * Los textos entre [corchetes] son para que el cliente los reemplace antes
 * de enviar; la página los resalta.
 */

export type Respuesta = { pt: string; es: string };

export type Mensaje = {
  id: string;
  /** Lo que el cliente quiere decir, en español (título de la tarjeta). */
  pregunta: string;
  /** Mensaje listo para copiar, en portugués. */
  pt: string;
  /** Traducción del mensaje al español. */
  es: string;
  /** Consejo de negociación (opcional). */
  tip?: string;
  /** Respuestas típicas del proveedor, para que el cliente entienda qué le contestan. */
  respuestas?: Respuesta[];
  /** Palabras extra para la búsqueda. */
  claves?: string;
};

export type Seccion = { id: string; titulo: string; descripcion?: string; mensajes: Mensaje[] };

export type Bloque = {
  id: string;
  titulo: string;
  emoji: string;
  /** Categorías del catálogo que cubre este bloque (texto informativo). */
  cubre?: string;
  descripcion: string;
  secciones: Seccion[];
};

type Extra = Partial<Omit<Mensaje, 'id' | 'pregunta' | 'pt' | 'es'>>;
type MensajeSinId = Omit<Mensaje, 'id'>;
type SeccionSinId = { titulo: string; descripcion?: string; mensajes: MensajeSinId[] };

const m = (pregunta: string, pt: string, es: string, extra: Extra = {}): MensajeSinId => ({ pregunta, pt, es, ...extra });
const r = (pt: string, es: string): Respuesta => ({ pt, es });
const sec = (titulo: string, mensajes: MensajeSinId[], descripcion?: string): SeccionSinId => ({ titulo, descripcion, mensajes });

function slug(s: string) {
  return s.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');
}

function bloque(b: Omit<Bloque, 'secciones'> & { secciones: SeccionSinId[] }): Bloque {
  return {
    ...b,
    secciones: b.secciones.map((s, i) => {
      const sid = `${b.id}-${i + 1}-${slug(s.titulo)}`;
      return { ...s, id: sid, mensajes: s.mensajes.map((msg, j) => ({ ...msg, id: `${sid}-${j + 1}` })) };
    }),
  };
}

